import PDFDocument from 'pdfkit';
import { formatInrFromPaise } from './upi.ts';

export interface ReceiptPdfData {
  receiptNumber: string;
  issuedAt: Date;
  category: string;
  paymentRef: string;
  invoiceRef: string;
  projectRef: string;
  projectName: string;
  customerRef: string;
  customerName: string;
  customerEmail: string;
  paidAmountPaise: number;
  currency: string;
  verifiedUtr: string;
  paymentMethod: string;
  businessIdentity: { legalName: string; address: string; email: string };
  taxDetails: { taxRegime: string; gstin: string; note: string };
}

export function renderReceiptPdfBuffer(data: ReceiptPdfData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const chunks: Buffer[] = [];
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    // Header
    doc.fontSize(20).fillColor('#0f172a').text(data.businessIdentity.legalName || 'ForgeX');
    doc
      .fontSize(9)
      .fillColor('#475569')
      .text(data.businessIdentity.address || 'Business address not yet configured')
      .text(data.businessIdentity.email || 'ForgeX 4XPay Payment Verification System');

    doc.moveUp(2.5);
    doc
      .fontSize(14)
      .fillColor('#0f172a')
      .text('PAYMENT RECEIPT', { align: 'right' });
    doc
      .fontSize(10)
      .fillColor('#16a34a')
      .text('VERIFIED CREDIT', { align: 'right' });
    doc
      .fontSize(9)
      .fillColor('#475569')
      .text(`Receipt No: ${data.receiptNumber}`, { align: 'right' })
      .text(`Verified Date (UTC): ${data.issuedAt.toISOString().slice(0, 19).replace('T', ' ')}`, {
        align: 'right',
      });

    doc.moveDown(2);
    doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#cbd5e1').stroke();
    doc.moveDown(1.2);

    // Customer & Project Details
    const topY = doc.y;
    doc.fontSize(9).fillColor('#64748b').text('RECEIVED FROM', 50, topY);
    doc.fontSize(11).fillColor('#0f172a').text(data.customerName, 50, topY + 14);
    doc
      .fontSize(9)
      .fillColor('#475569')
      .text(`Customer ID: ${data.customerRef}`, 50, topY + 30)
      .text(data.customerEmail, 50, topY + 44);

    doc.fontSize(9).fillColor('#64748b').text('PROJECT & INVOICE', 300, topY);
    doc.fontSize(11).fillColor('#0f172a').text(data.projectName, 300, topY + 14);
    doc
      .fontSize(9)
      .fillColor('#475569')
      .text(`Project ID: ${data.projectRef}`, 300, topY + 30)
      .text(`Invoice Ref: ${data.invoiceRef}`, 300, topY + 44);

    doc.moveDown(4.5);

    // Payment Summary Table
    const boxY = doc.y;
    doc.rect(50, boxY, 495, 130).fillAndStroke('#f8fafc', '#e2e8f0');

    const rows: Array<[string, string]> = [
      ['ForgeX Payment ID', data.paymentRef],
      ['Payment Category', `${data.category} Payment`],
      ['Payment Method', data.paymentMethod],
      ['Verified Bank Reference / UTR', data.verifiedUtr],
      ['Verified Amount Received', `${formatInrFromPaise(data.paidAmountPaise)} (${data.currency})`],
    ];

    let rowY = boxY + 14;
    for (const [label, val] of rows) {
      doc.fontSize(9).fillColor('#475569').text(label, 68, rowY);
      doc
        .fontSize(10)
        .fillColor('#0f172a')
        .text(val, 260, rowY, { width: 265, align: 'right' });
      rowY += 22;
    }

    doc.moveDown(3);
    doc.y = boxY + 152;

    // Explicit Tax Disclosure (Never invent GSTIN!)
    doc.fontSize(9).fillColor('#0f172a').text('Tax & Compliance Information');
    if (data.taxDetails.taxRegime === 'GST' && data.taxDetails.gstin) {
      doc
        .fontSize(8.5)
        .fillColor('#475569')
        .text(`GSTIN: ${data.taxDetails.gstin}`)
        .text(data.taxDetails.note || 'Tax treatment applied as per configured GST profile.');
    } else if (data.taxDetails.taxRegime === 'NON_GST') {
      doc
        .fontSize(8.5)
        .fillColor('#475569')
        .text('Tax Regime: Non-GST / Unregistered Entity. No GST charged on this receipt.');
    } else {
      doc
        .fontSize(8.5)
        .fillColor('#b45309')
        .text(
          'Tax registration details are currently UNCONFIGURED. This document serves as a verified payment receipt only and is not a GST tax invoice.'
        );
    }

    doc.moveDown(2);
    doc
      .fontSize(8)
      .fillColor('#64748b')
      .text(
        'Generated by ForgeX 4XPay. This receipt is issued strictly following backend verification of the incoming bank credit. ForgeX 4XPay is a private internal payment management platform and is not a licensed bank or payment aggregator.'
      );

    doc.end();
  });
}

export interface InvoicePdfData {
  invoiceRef: string;
  title: string;
  status: string;
  issuedAt: Date;
  dueDate: Date | null;
  projectRef: string;
  projectName: string;
  customerRef: string;
  customerName: string;
  customerEmail: string;
  subtotalPaise: number;
  taxPaise: number;
  totalPaise: number;
  verifiedPaidPaise: number;
  currency: string;
  taxRegime: string;
  businessGstin: string;
  businessIdentity: { legalName: string; address: string; email: string };
  items: Array<{ description: string; category: string; quantity: number; totalPaise: number }>;
}

export function renderInvoicePdfBuffer(data: InvoicePdfData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const chunks: Buffer[] = [];
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.fontSize(20).fillColor('#0f172a').text(data.businessIdentity.legalName || 'ForgeX');
    doc
      .fontSize(9)
      .fillColor('#475569')
      .text(data.businessIdentity.address || 'Business address not yet configured');

    doc.moveUp(1.5);
    doc.fontSize(14).fillColor('#0f172a').text('INVOICE', { align: 'right' });
    doc
      .fontSize(9)
      .fillColor('#475569')
      .text(`Invoice Ref: ${data.invoiceRef}`, { align: 'right' })
      .text(`Status: ${data.status}`, { align: 'right' })
      .text(`Issued: ${data.issuedAt.toISOString().slice(0, 10)}`, { align: 'right' });

    doc.moveDown(2);
    doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#cbd5e1').stroke();
    doc.moveDown(1);

    doc.fontSize(10).fillColor('#0f172a').text(`Billed To: ${data.customerName} (${data.customerRef})`);
    doc.fontSize(9).fillColor('#475569').text(data.customerEmail);
    doc.text(`Project: ${data.projectName} (${data.projectRef})`);
    doc.moveDown(1.5);

    // Line items
    doc.fontSize(9).fillColor('#64748b').text('DESCRIPTION', 50, doc.y);
    doc.text('CATEGORY', 310, doc.y - 11);
    doc.text('AMOUNT', 430, doc.y - 11, { width: 115, align: 'right' });
    doc.moveDown(0.5);
    doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#e2e8f0').stroke();
    doc.moveDown(0.6);

    for (const item of data.items) {
      const y = doc.y;
      doc.fontSize(9.5).fillColor('#0f172a').text(item.description, 50, y, { width: 250 });
      doc.fontSize(9).fillColor('#475569').text(item.category, 310, y);
      doc
        .fontSize(9.5)
        .fillColor('#0f172a')
        .text(formatInrFromPaise(item.totalPaise), 430, y, { width: 115, align: 'right' });
      doc.moveDown(0.9);
    }

    doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#e2e8f0').stroke();
    doc.moveDown(0.8);

    const outstanding = Math.max(0, data.totalPaise - data.verifiedPaidPaise);
    const summaryRows: Array<[string, string]> = [
      ['Subtotal', formatInrFromPaise(data.subtotalPaise)],
      ['Tax', formatInrFromPaise(data.taxPaise)],
      ['Invoice Total', formatInrFromPaise(data.totalPaise)],
      ['Verified Paid', formatInrFromPaise(data.verifiedPaidPaise)],
      ['Outstanding Balance', formatInrFromPaise(outstanding)],
    ];

    for (const [lbl, val] of summaryRows) {
      const y = doc.y;
      doc.fontSize(9.5).fillColor('#475569').text(lbl, 310, y);
      doc.fontSize(10).fillColor('#0f172a').text(val, 430, y, { width: 115, align: 'right' });
      doc.moveDown(0.6);
    }

    doc.moveDown(1.5);
    if (data.taxRegime === 'GST' && data.businessGstin) {
      doc.fontSize(8.5).fillColor('#475569').text(`GSTIN: ${data.businessGstin}`);
    } else {
      doc
        .fontSize(8.5)
        .fillColor('#b45309')
        .text(`Tax Profile: ${data.taxRegime}. Configure GST details in Settings before issuing tax invoices.`);
    }

    doc.end();
  });
}
